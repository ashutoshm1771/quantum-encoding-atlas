class ExpressibilityResult(TypedDict):
    """Result dictionary from expressibility computation.

    This TypedDict defines the structure of the result returned by
    :func:`compute_expressibility` when ``return_distributions=True``.

    Attributes
    ----------
    expressibility : float
        Normalized expressibility score in [0, 1]. Higher values indicate
        the encoding's fidelity distribution is closer to Haar-random,
        meaning it can explore more of the Hilbert space.
    kl_divergence : float
        Raw Kullback-Leibler divergence from the encoding's fidelity
        distribution to the Haar distribution. Lower values indicate
        higher expressibility.
    fidelity_distribution : NDArray[np.floating]
        Histogram of sampled fidelities (probability for each bin).
        Shape: (n_bins,). Values sum to approximately 1.
    haar_distribution : NDArray[np.floating]
        Theoretical Haar-random fidelity distribution evaluated at
        the same bin centers. Shape: (n_bins,).
    bin_edges : NDArray[np.floating]
        Edges of the histogram bins. Shape: (n_bins + 1,).
        Range is [0, 1] for fidelity values.
    n_samples : int
        Number of fidelity samples used in the computation.
    n_bins : int
        Number of histogram bins used.
    convergence_estimate : float
        Bootstrap estimate of the standard error of the KL divergence.
        Smaller values indicate more reliable results.
    mean_fidelity : float
        Mean of the sampled fidelities. Useful for understanding
        the typical overlap between encoded states.
    std_fidelity : float
        Standard deviation of the sampled fidelities.
    expressibility_ci_lower : float
        Lower bound of the percentile bootstrap confidence interval on
        ``expressibility`` at ``confidence_level``. Computed by
        resampling the per-sample fidelity array and re-running the
        full histogram → KL → score pipeline on each resample.
    expressibility_ci_upper : float
        Upper bound of the percentile bootstrap CI on ``expressibility``.
    mean_fidelity_ci_lower : float
        Lower bound of the bootstrap CI on ``mean_fidelity``.
    mean_fidelity_ci_upper : float
        Upper bound of the bootstrap CI on ``mean_fidelity``.
    confidence_level : float
        Two-sided confidence level used for the CI bounds above
        (default 0.95 → 95% CIs).
    sampling : {'uniform', 'sobol'}
        Sampling strategy that produced the fidelity pairs. See
        :func:`compute_expressibility` for details.

    Examples
    --------
    >>> result = compute_expressibility(enc, return_distributions=True, seed=42)
    >>> print(f"Expressibility: {result['expressibility']:.4f}")
    >>> print(f"KL Divergence: {result['kl_divergence']:.4f}")
    >>> print(f"Mean Fidelity: {result['mean_fidelity']:.4f}")
    >>> lo, hi = result['expressibility_ci_lower'], result['expressibility_ci_upper']
    >>> print(f"95% CI: [{lo:.4f}, {hi:.4f}]")
    """

    expressibility: float
    kl_divergence: float
    fidelity_distribution: NDArray[np.floating[Any]]
    haar_distribution: NDArray[np.floating[Any]]
    bin_edges: NDArray[np.floating[Any]]
    n_samples: int
    n_bins: int
    convergence_estimate: float
    mean_fidelity: float
    std_fidelity: float
    expressibility_ci_lower: float
    expressibility_ci_upper: float
    mean_fidelity_ci_lower: float
    mean_fidelity_ci_upper: float
    confidence_level: float
    sampling: str


