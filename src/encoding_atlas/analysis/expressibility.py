def _sample_fidelities(
    encoding: BaseEncoding,
    n_samples: int,
    n_features: int,
    input_range: tuple[float, float],
    rng: np.random.Generator,
    backend: str,
    verbose: bool,
) -> NDArray[np.floating[Any]]:
    """Sample fidelities between random input pairs.

    This is the core sampling loop for expressibility computation.
    For each of n_samples iterations:
    1. Generate two random input vectors x1, x2
    2. Simulate encoding to get states |ψ(x1)⟩, |ψ(x2)⟩
    3. Compute fidelity F = |⟨ψ(x1)|ψ(x2)⟩|²

    Parameters
    ----------
    encoding : BaseEncoding
        The encoding to analyze.
    n_samples : int
        Number of fidelity samples to generate.
    n_features : int
        Number of features in the encoding.
    input_range : tuple[float, float]
        (min, max) range for random input sampling.
    rng : np.random.Generator
        Random number generator for reproducibility.
    backend : str
        Backend for circuit simulation.
    verbose : bool
        If True, log progress.

    Returns
    -------
    NDArray[np.floating]
        Array of fidelity values, shape (n_samples,).

    Raises
    ------
    SimulationError
        If circuit simulation fails.
    """
    # TODO: Vectorize this loop — batch rng.uniform calls and simulation
    # calls to reduce per-sample overhead. This is the main performance
    # bottleneck for large n_samples. See simulate_encoding_statevectors_batch
    # in _utils.py for a possible starting point.
    fidelities = np.zeros(n_samples, dtype=np.float64)

    # Logging interval (log every 10% of progress)
    log_interval = max(1, n_samples // 10)

    for i in range(n_samples):
        # Generate two random input vectors
        x1 = rng.uniform(input_range[0], input_range[1], size=n_features)
        x2 = rng.uniform(input_range[0], input_range[1], size=n_features)

        try:
            # Simulate encoding to get statevectors
            state1 = simulate_encoding_statevector(encoding, x1, backend=backend)
            state2 = simulate_encoding_statevector(encoding, x2, backend=backend)

            # Compute fidelity: F = |⟨ψ₁|ψ₂⟩|²
            fidelity = compute_fidelity(state1, state2)

            # Clamp to [0, 1] for numerical safety
            fidelities[i] = float(np.clip(fidelity, 0.0, 1.0))

        except SimulationError:
            # Re-raise simulation errors with context
            raise
        except Exception as e:
            raise SimulationError(
                f"Failed to compute fidelity at sample {i}/{n_samples}: {e}",
                backend=backend,
                details={
                    "sample_index": i,
                    "error_type": type(e).__name__,
                    "error_message": str(e),
                },
            ) from e

        # Log progress
        if verbose and (i + 1) % log_interval == 0:
            _logger.debug(
                "Sampled %d/%d fidelities (%.1f%%)",
                i + 1,
                n_samples,
                100.0 * (i + 1) / n_samples,
            )

    return fidelities


def _estimate_convergence(
    fidelities: NDArray[np.floating[Any]],
    n_bins: int,
    n_qubits: int,
    rng: np.random.Generator,
    n_bootstrap: int = _DEFAULT_N_BOOTSTRAP,
) -> float:
    """Estimate statistical convergence via bootstrap resampling.

    Performs bootstrap resampling to estimate the standard error of the
    KL divergence estimate. This provides a measure of how much the
    expressibility value would change with different random samples.

    Parameters
    ----------
    fidelities : NDArray[np.floating]
        Sampled fidelity values.
    n_bins : int
        Number of histogram bins.
    n_qubits : int
        Number of qubits (for Haar distribution).
    rng : np.random.Generator
        Random number generator.
    n_bootstrap : int
        Number of bootstrap samples.

    Returns
    -------
    float
        Standard error estimate for the KL divergence.
        Smaller values indicate more stable/reliable results.
    """
    n_samples = len(fidelities)

    # Quick return if too few samples for meaningful bootstrap
    if n_samples < 20:
        return float("inf")

    bootstrap_kls = np.zeros(n_bootstrap, dtype=np.float64)

    # Pre-compute Haar distribution (same for all bootstrap samples)
    bin_edges = np.linspace(0.0, 1.0, n_bins + 1)
    bin_centers = (bin_edges[:-1] + bin_edges[1:]) / 2.0
    P_haar = compute_haar_distribution(n_qubits, bin_centers)
    P_haar_safe = P_haar + _NUMERICAL_EPSILON
    P_haar_safe = P_haar_safe / P_haar_safe.sum()

    bin_width = bin_edges[1] - bin_edges[0]

    for b in range(n_bootstrap):
        # Resample with replacement
        boot_indices = rng.choice(n_samples, size=n_samples, replace=True)
        boot_fidelities = fidelities[boot_indices]

        # Compute histogram for bootstrap sample
        hist, _ = np.histogram(
            boot_fidelities,
            bins=n_bins,
            range=(0.0, 1.0),
            density=True,
        )

        # Convert to probability mass
        P_boot = hist * bin_width
        P_boot_sum = P_boot.sum()
        if P_boot_sum > _NUMERICAL_EPSILON:
            P_boot = P_boot / P_boot_sum

        # Add epsilon and renormalize
        P_boot_safe = P_boot + _NUMERICAL_EPSILON
        P_boot_safe = P_boot_safe / P_boot_safe.sum()

        # Compute KL divergence
        kl_array = rel_entr(P_boot_safe, P_haar_safe)
        kl_val: float = float(np.sum(kl_array))

        # Handle numerical issues
        if np.isnan(kl_val) or np.isinf(kl_val):
            kl_val = _MAX_KL_DIVERGENCE

        bootstrap_kls[b] = kl_val

    # Return standard deviation of bootstrap KL values
    return float(np.std(bootstrap_kls, ddof=1))
