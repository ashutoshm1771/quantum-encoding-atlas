def compute_expressibility(
    encoding: BaseEncoding,
    n_samples: int = _DEFAULT_N_SAMPLES,
    n_bins: int | None = None,
    input_range: tuple[float, float] = _DEFAULT_INPUT_RANGE,
    seed: int | None = None,
    backend: Literal["pennylane", "qiskit", "cirq"] = "pennylane",
    return_distributions: bool = False,
    verbose: bool = False,
    parallel: ParallelArg = False,
    max_workers: int | None = None,
    sampling: SamplingMethod = "uniform",
    confidence_level: float = _DEFAULT_CONFIDENCE_LEVEL,
    n_bootstrap_ci: int = _DEFAULT_N_BOOTSTRAP_CI,
) -> float | ExpressibilityResult:
    """Compute the expressibility of a quantum encoding.

    Expressibility quantifies how well the encoding can explore the Hilbert
    space compared to Haar-random states. Higher expressibility (closer to 1.0)
    indicates the encoding can generate a more diverse set of quantum states,
    which is generally desirable for variational quantum algorithms.

    The computation works by:

    1. Sampling random input pairs and computing their quantum states
    2. Computing fidelities between state pairs
    3. Building a histogram of fidelities
    4. Comparing to the theoretical Haar-random distribution via KL divergence
    5. Normalizing to a [0, 1] score

    Parameters
    ----------
    encoding : BaseEncoding
        The encoding instance to analyze. Must have ``n_features`` and
        ``n_qubits`` attributes and implement ``get_circuit()``.
    n_samples : int, default=5000
        Number of random input pairs to sample. Higher values give more
        accurate results but increase computation time. A minimum of 1000
        samples is recommended for reliable results.
    n_bins : int or None, default=None
        Number of bins for the fidelity histogram. If None (default),
        automatically set to ``min(75, n_samples)`` so that small sample
        counts don't require manually tuning the bin count. If provided
        explicitly, must satisfy ``10 ≤ n_bins ≤ n_samples``.
        Rule of thumb: n_bins ≈ √n_samples.
    input_range : tuple[float, float], default=(0, 2π)
        Range for sampling random input values. The default covers the
        full rotation range for typical quantum gates.
    seed : int, optional
        Random seed for reproducibility. If None, results will vary
        between runs. Always specify a seed for reproducible analysis.
    backend : {"pennylane", "qiskit", "cirq"}, default="pennylane"
        Backend to use for circuit simulation.

        - ``"pennylane"``: Uses PennyLane's default.qubit simulator (recommended)
        - ``"qiskit"``: Uses Qiskit's Statevector class
        - ``"cirq"``: Uses Cirq's Simulator for statevector simulation
    return_distributions : bool, default=False
        If True, return full result dictionary including fidelity
        distributions, bin edges, and statistics.
        If False, return only the expressibility score (float).
    verbose : bool, default=False
        If True, log progress information during computation.
    parallel : bool or {'thread', 'process'}, default=False
        Parallel-dispatch mode for the per-sample fidelity computation.
        Each sample requires two independent statevector simulations,
        making the loop embarrassingly parallel.

        - ``False`` (default) — sequential, no executor overhead.
        - ``True`` or ``'thread'`` — :class:`ThreadPoolExecutor`. Useful
          when the backend simulator releases the GIL during numerical
          work (NumPy operations typically do).
        - ``'process'`` — :class:`ProcessPoolExecutor` for true CPU
          parallelism. The encoding is pickled once per worker. Best
          for large ``n_samples`` and CPU-bound backends. Has
          process-startup overhead, so only worthwhile for batches of
          roughly 100+ samples. Workers exchange only NumPy arrays /
          floats, so process-pool parallelism works with **all** three
          backends here (unlike ``BaseEncoding.get_circuits`` where
          PennyLane's local-closure qfuncs prevent process-pool use).

        Output is numerically identical across all modes for a fixed
        ``seed``: the RNG is fully consumed in the main process before
        any work is dispatched to workers.
    max_workers : int or None, default=None
        Maximum number of workers when ``parallel`` is enabled.
        ``None`` defers to the executor's default (typically based on
        CPU count).
    sampling : {'uniform', 'sobol'}, default='uniform'
        Strategy for drawing the random input pairs ``(X1, X2)``:

        - ``'uniform'`` (default, unchanged behavior): pseudo-random
          i.i.d. samples via :meth:`numpy.random.Generator.uniform`.
        - ``'sobol'``: Sobol' low-discrepancy quasi-random sequence
          via :class:`scipy.stats.qmc.Sobol`. Covers the hypercube
          much more evenly than i.i.d. uniform draws and typically
          reaches the same KL accuracy with **30-50% fewer samples**.
          For best statistical properties round ``n_samples`` up to
          the nearest power of two.

        Sobol is seeded from the same ``seed`` argument so a given
        ``(seed, sampling)`` pair is fully reproducible.
    confidence_level : float, default=0.95
        Two-sided confidence level for the bootstrap CIs reported in
        the result dict (only used when ``return_distributions=True``).
        Must lie strictly in ``(0, 1)``. Common choices: 0.90, 0.95,
        0.99.
    n_bootstrap_ci : int, default=200
        Number of bootstrap resamples used to estimate the
        ``expressibility`` and ``mean_fidelity`` percentile CIs
        (only when ``return_distributions=True``). 200 stabilizes
        the percentile endpoints to ~1% jitter; raise to ~1000 for
        publication-grade precision.

    Returns
    -------
    float or ExpressibilityResult
        If ``return_distributions=False``: Expressibility score in [0, 1].
        Higher values indicate more expressive encodings.

        If ``return_distributions=True``: Dictionary containing:

        - **expressibility**: float in [0, 1], higher = more expressive
        - **kl_divergence**: raw KL divergence value
        - **fidelity_distribution**: sampled fidelity histogram
        - **haar_distribution**: theoretical Haar distribution
        - **bin_edges**: histogram bin edges
        - **n_samples**: number of samples used
        - **n_bins**: number of histogram bins
        - **convergence_estimate**: bootstrap standard error estimate
        - **mean_fidelity**: mean of sampled fidelities
        - **std_fidelity**: standard deviation of sampled fidelities

    Raises
    ------
    InsufficientSamplesError
        If ``n_samples < 10`` (too few for meaningful statistics).
    SimulationError
        If circuit simulation fails for the given backend.
    AnalysisError
        If encoding is invalid or computation fails.
    ValueError
        If explicit ``n_bins < 10`` or ``n_bins > n_samples``, or if
        ``input_range[0] >= input_range[1]``.

    Warns
    -----
    UserWarning
        If ``n_samples < 100`` (results may be unreliable).
    UserWarning
        If encoding has > 10 qubits (computation may be slow).

    Examples
    --------
    Basic usage with default parameters:

    >>> from encoding_atlas import AngleEncoding
    >>> enc = AngleEncoding(n_features=4)
    >>> expr = compute_expressibility(enc, seed=42)
    >>> print(f"Expressibility: {expr:.4f}")
    Expressibility: ...

    Get full result with distributions:

    >>> result = compute_expressibility(enc, return_distributions=True, seed=42)
    >>> print(f"KL Divergence: {result['kl_divergence']:.4f}")
    >>> print(f"Samples used: {result['n_samples']}")

    Compare two encodings:

    >>> from encoding_atlas import IQPEncoding
    >>> enc1 = AngleEncoding(n_features=4)  # Non-entangling
    >>> enc2 = IQPEncoding(n_features=4, reps=2)  # Entangling
    >>> expr1 = compute_expressibility(enc1, n_samples=1000, seed=42)
    >>> expr2 = compute_expressibility(enc2, n_samples=1000, seed=42)
    >>> print(f"AngleEncoding: {expr1:.4f}")
    >>> print(f"IQPEncoding: {expr2:.4f}")
    >>> # IQP typically shows higher expressibility due to entanglement

    Notes
    -----
    **Computational Complexity**

    The complexity is O(n_samples × simulation_cost), where simulation_cost
    scales as O(2^n_qubits). For encodings with more than 10 qubits,
    consider reducing n_samples or using approximate methods.

    **Interpretation**

    - Expressibility ≈ 0: Encoding produces states in a narrow region
      of Hilbert space (e.g., product states only)
    - Expressibility ≈ 1: Encoding produces states distributed like
      Haar-random states (explores full Hilbert space)

    **Normalization Formula**

    The expressibility score is normalized from KL divergence using::

        expr = 1.0 - min(1.0, kl_divergence / MAX_KL)

    This maps KL divergence to [0, 1] where higher values indicate
    distributions closer to Haar-random (more expressive).

    **Statistical Reliability**

    The ``convergence_estimate`` in the result dictionary provides a
    bootstrap estimate of the standard error. Values < 0.05 generally
    indicate reliable results.

    See Also
    --------
    compute_fidelity_distribution : Compute fidelity distribution only.
    compute_haar_distribution : Compute theoretical Haar distribution.
    compute_entanglement_capability : Related metric for entanglement.

    References
    ----------
    .. [1] Sim, S., Johnson, P. D., & Aspuru-Guzik, A. (2019).
           "Expressibility and entangling capability of parameterized
           quantum circuits for hybrid quantum-classical algorithms."
           Advanced Quantum Technologies, 2(12), 1900070.
    """
    # =========================================================================
    # Input Validation
    # =========================================================================

    # Validate encoding
    validate_encoding_for_analysis(encoding)

    # Validate n_samples
    if not isinstance(n_samples, int) or n_samples < 1:
        raise ValueError(f"n_samples must be a positive integer, got {n_samples}")

    if n_samples < _MIN_SAMPLES_ERROR:
        raise InsufficientSamplesError(
            f"n_samples must be at least {_MIN_SAMPLES_ERROR} for meaningful "
            f"statistics, got {n_samples}. Recommended minimum: "
            f"{_MIN_SAMPLES_WARNING}.",
            requested_samples=n_samples,
            minimum_samples=_MIN_SAMPLES_ERROR,
            metric="expressibility",
        )

    if n_samples < _MIN_SAMPLES_WARNING:
        warnings.warn(
            f"n_samples={n_samples} is low; results may be unreliable. "
            f"Recommended minimum: {_MIN_SAMPLES_WARNING}.",
            UserWarning,
            stacklevel=2,
        )

    # Resolve n_bins: auto-select when not specified, validate when explicit
    if n_bins is None:
        # Auto-select: use the default, clamped to n_samples so that users
        # who simply pass a small n_samples don't hit an unexpected error.
        n_bins = min(_DEFAULT_N_BINS, n_samples)
    else:
        # User explicitly provided n_bins — validate strictly
        if not isinstance(n_bins, int) or n_bins < 1:
            raise ValueError(f"n_bins must be a positive integer, got {n_bins}")

        if n_bins < 10:
            raise ValueError(
                f"n_bins must be at least 10 for meaningful histogram, got {n_bins}"
            )

        if n_bins > n_samples:
            raise ValueError(
                f"n_bins ({n_bins}) cannot exceed n_samples ({n_samples}). "
                f"Reduce n_bins or increase n_samples."
            )

    # Validate input_range
    if len(input_range) != 2:
        raise ValueError(f"input_range must have 2 elements, got {len(input_range)}")

    if input_range[0] >= input_range[1]:
        raise ValueError(
            f"input_range[0] must be less than input_range[1], "
            f"got [{input_range[0]}, {input_range[1]}]"
        )

    # Validate parallel argument early so a bad value surfaces as a clean
    # ``ValueError`` instead of being wrapped in ``AnalysisError`` by the
    # broad ``except`` around the sampling loop below.
    resolve_parallel_mode(parallel)

    # Validate sampling/CI arguments upfront for the same reason — bad
    # values must surface as plain ValueErrors before any expensive work.
    validate_sampling(sampling)
    validate_ci_args(confidence_level, n_bootstrap_ci)

    # Warn about large qubit counts
    n_qubits = encoding.n_qubits
    if n_qubits > _QUBIT_WARNING_THRESHOLD:
        warnings.warn(
            f"Encoding has {n_qubits} qubits. Computation may be slow due "
            f"to exponential scaling of simulation. Consider using fewer "
            f"samples or a smaller encoding for testing.",
            UserWarning,
            stacklevel=2,
        )

    # Validate backend
    if backend not in ("pennylane", "qiskit", "cirq"):
        raise ValueError(
            f"backend must be 'pennylane', 'qiskit', or 'cirq', got {backend!r}"
        )

    # =========================================================================
    # Setup
    # =========================================================================

    rng = create_rng(seed)
    n_features = encoding.n_features

    if verbose:
        _logger.info(
            "Computing expressibility for %s (n_qubits=%d, n_features=%d, "
            "n_samples=%d, n_bins=%d)",
            encoding.__class__.__name__,
            n_qubits,
            n_features,
            n_samples,
            n_bins,
        )

    # =========================================================================
    # Sample Fidelities
    # =========================================================================

    try:
        fidelities = _sample_fidelities(
            encoding=encoding,
            n_samples=n_samples,
            n_features=n_features,
            input_range=input_range,
            rng=rng,
            backend=backend,
            verbose=verbose,
            parallel=parallel,
            max_workers=max_workers,
            sampling=sampling,
        )
    except SimulationError:
        raise
    except Exception as e:
        raise AnalysisError(
            f"Failed to sample fidelities for {encoding.__class__.__name__}: {e}",
            details={"error_type": type(e).__name__, "error_message": str(e)},
        ) from e

    # =========================================================================
    # Build Histogram
    # =========================================================================

    # Fidelity is in [0, 1], use fixed bins for consistency
    # density=True normalizes so that integral over bins equals 1
    hist_encoding, bin_edges = np.histogram(
        fidelities,
        bins=n_bins,
        range=(0.0, 1.0),
        density=True,
    )

    # Convert density to probability mass function
    # For uniform bins: P_i = density_i × bin_width
    bin_width = bin_edges[1] - bin_edges[0]
    P_encoding = hist_encoding * bin_width

    # Ensure proper normalization (should already sum to ~1)
    P_encoding_sum = P_encoding.sum()
    if P_encoding_sum > _NUMERICAL_EPSILON:
        P_encoding = P_encoding / P_encoding_sum
    else:
        # Degenerate case: fidelity distribution has near-zero total probability mass.
        # This can occur when:
        # 1. All fidelities are concentrated in a single bin (encoding produces
        #    nearly identical states for all inputs)
        # 2. Numerical underflow in histogram computation
        # 3. Very few unique fidelity values that don't span the histogram range
        #
        # We fall back to a uniform distribution to ensure KL divergence computation
        # remains numerically stable. This is a conservative choice that will result
        # in a meaningful (though potentially less accurate) expressibility estimate.
        _logger.warning(
            "Fidelity distribution is degenerate (sum=%.2e). This may indicate the "
            "encoding produces nearly identical states for all inputs, or numerical "
            "issues in histogram computation. Falling back to uniform distribution "
            "for KL divergence computation. Consider increasing n_samples or "
            "checking the encoding's behavior.",
            P_encoding_sum,
        )
        P_encoding = np.ones(n_bins, dtype=np.float64) / n_bins

    # =========================================================================
    # Compute Haar Distribution
    # =========================================================================

    # Evaluate at bin centers for comparison
    bin_centers = (bin_edges[:-1] + bin_edges[1:]) / 2.0
    P_haar = compute_haar_distribution(n_qubits, bin_centers)

    # =========================================================================
    # Compute KL Divergence
    # =========================================================================

    # Add epsilon to prevent log(0) and handle zero probabilities
    P_encoding_safe = P_encoding + _NUMERICAL_EPSILON
    P_haar_safe = P_haar + _NUMERICAL_EPSILON

    # Renormalize after adding epsilon
    P_encoding_safe = P_encoding_safe / P_encoding_safe.sum()
    P_haar_safe = P_haar_safe / P_haar_safe.sum()

    # Compute KL(P_encoding || P_haar) using scipy's rel_entr
    # rel_entr(p, q) = p * log(p/q) with proper handling of zeros
    kl_divergence_array = rel_entr(P_encoding_safe, P_haar_safe)

    # Check for numerical issues
    if np.any(np.isnan(kl_divergence_array)) or np.any(np.isinf(kl_divergence_array)):
        raise NumericalInstabilityError(
            "KL divergence computation produced NaN or Inf values. "
            "This may indicate numerical instability in the distribution.",
            operation="compute_kl_divergence",
            details={
                "has_nan": bool(np.any(np.isnan(kl_divergence_array))),
                "has_inf": bool(np.any(np.isinf(kl_divergence_array))),
            },
        )

    kl_divergence = float(np.sum(kl_divergence_array))

    # Ensure non-negative (can be slightly negative due to numerical error)
    if kl_divergence < 0:
        if kl_divergence < -_NUMERICAL_EPSILON:
            _logger.warning(
                "KL divergence is negative (%.6e), clamping to 0", kl_divergence
            )
        kl_divergence = 0.0

    # =========================================================================
    # Normalize to Expressibility Score
    # =========================================================================

    # Lower KL = more expressive, so we invert and normalize
    # expressibility = 1 - min(1, KL/MAX_KL)
    expressibility = 1.0 - min(1.0, kl_divergence / _MAX_KL_DIVERGENCE)

    # Clamp to [0, 1] for safety
    expressibility = float(np.clip(expressibility, 0.0, 1.0))

    # =========================================================================
    # Estimate Convergence / Statistical Error
    # =========================================================================

    convergence_estimate = _estimate_convergence(
        fidelities=fidelities,
        n_bins=n_bins,
        n_qubits=n_qubits,
        rng=rng,
        n_bootstrap=_DEFAULT_N_BOOTSTRAP,
    )

    # =========================================================================
    # Compute Additional Statistics
    # =========================================================================

    mean_fidelity = float(np.mean(fidelities))
    std_fidelity = float(np.std(fidelities, ddof=1))

    if verbose:
        _logger.info(
            "Expressibility: %.4f (KL=%.4f, mean_fid=%.4f, convergence=%.4f)",
            expressibility,
            kl_divergence,
            mean_fidelity,
            convergence_estimate,
        )

    # =========================================================================
    # Bootstrap Confidence Intervals (only for the detailed result)
    # =========================================================================
    #
    # The CI cost is bounded by ``n_bootstrap_ci`` × histogram-pipeline-cost,
    # which is negligible next to the ``n_samples`` simulations we already
    # paid for above. We only compute them when the caller asked for the
    # detailed result; the float-only return path stays fast.

    if return_distributions:
        expressibility_ci = _bootstrap_expressibility_ci(
            fidelities=fidelities,
            n_bins=n_bins,
            n_qubits=n_qubits,
            rng=rng,
            n_bootstrap=n_bootstrap_ci,
            confidence_level=confidence_level,
        )
        mean_fidelity_ci = percentile_bootstrap_ci(
            samples=fidelities,
            statistic_fn=np.mean,
            rng=rng,
            n_bootstrap=n_bootstrap_ci,
            confidence_level=confidence_level,
        )

    # =========================================================================
    # Return Results
    # =========================================================================

    if return_distributions:
        return ExpressibilityResult(
            expressibility=expressibility,
            kl_divergence=kl_divergence,
            fidelity_distribution=P_encoding.astype(np.float64),
            haar_distribution=P_haar.astype(np.float64),
            bin_edges=bin_edges.astype(np.float64),
            n_samples=n_samples,
            n_bins=n_bins,
            convergence_estimate=convergence_estimate,
            mean_fidelity=mean_fidelity,
            std_fidelity=std_fidelity,
            expressibility_ci_lower=expressibility_ci[0],
            expressibility_ci_upper=expressibility_ci[1],
            mean_fidelity_ci_lower=mean_fidelity_ci[0],
            mean_fidelity_ci_upper=mean_fidelity_ci[1],
            confidence_level=float(confidence_level),
            sampling=str(sampling),
        )

    return expressibility


def compute_fidelity_distribution(
    encoding: BaseEncoding,
    n_samples: int = _DEFAULT_N_SAMPLES,
    input_range: tuple[float, float] = _DEFAULT_INPUT_RANGE,
    seed: int | None = None,
    backend: Literal["pennylane", "qiskit", "cirq"] = "pennylane",
    parallel: ParallelArg = False,
    max_workers: int | None = None,
    sampling: SamplingMethod = "uniform",
) -> NDArray[np.floating[Any]]:
    """Compute the fidelity distribution for an encoding.

    Samples random input pairs and computes the fidelity between their
    corresponding quantum states. This is useful for analyzing the
    encoding's behavior without computing the full expressibility.

    Parameters
    ----------
    encoding : BaseEncoding
        The encoding to analyze.
    n_samples : int, default=5000
        Number of random input pairs to sample.
    input_range : tuple[float, float], default=(0, 2π)
        Range for random input sampling.
    seed : int, optional
        Random seed for reproducibility.
    backend : {"pennylane", "qiskit", "cirq"}, default="pennylane"
        Backend for circuit simulation.

        - ``"pennylane"``: Uses PennyLane's default.qubit simulator (recommended)
        - ``"qiskit"``: Uses Qiskit's Statevector class
        - ``"cirq"``: Uses Cirq's Simulator for statevector simulation
    parallel : bool or {'thread', 'process'}, default=False
        Parallel-dispatch mode for the per-sample fidelity computation.
        See :func:`compute_expressibility` for the full discussion.
    max_workers : int or None, default=None
        Maximum number of workers when ``parallel`` is enabled.
    sampling : {'uniform', 'sobol'}, default='uniform'
        Strategy for drawing the random input pairs. See
        :func:`compute_expressibility` for the full discussion.

    Returns
    -------
    NDArray[np.floating]
        Array of fidelity values, shape ``(n_samples,)``, each in [0, 1].

    Raises
    ------
    InsufficientSamplesError
        If ``n_samples < 10``.
    SimulationError
        If circuit simulation fails.
    AnalysisError
        If encoding is invalid.

    Examples
    --------
    >>> from encoding_atlas import IQPEncoding
    >>> enc = IQPEncoding(n_features=4, reps=1)
    >>> fidelities = compute_fidelity_distribution(enc, n_samples=1000, seed=42)
    >>> print(f"Mean fidelity: {fidelities.mean():.4f}")
    >>> print(f"Std fidelity: {fidelities.std():.4f}")

    Notes
    -----
    The fidelity F = |⟨ψ₁|ψ₂⟩|² measures the overlap between two quantum
    states. F = 1 means identical states (up to global phase), F = 0 means
    orthogonal states.

    For Haar-random states in high dimensions, most pairs have F ≈ 0
    because random high-dimensional vectors are typically nearly orthogonal.

    See Also
    --------
    compute_expressibility : Full expressibility computation.
    compute_haar_distribution : Theoretical Haar distribution.
    """
    # Validate inputs
    validate_encoding_for_analysis(encoding)

    if not isinstance(n_samples, int) or n_samples < 1:
        raise ValueError(f"n_samples must be a positive integer, got {n_samples}")

    if n_samples < _MIN_SAMPLES_ERROR:
        raise InsufficientSamplesError(
            f"n_samples must be at least {_MIN_SAMPLES_ERROR}, got {n_samples}",
            requested_samples=n_samples,
            minimum_samples=_MIN_SAMPLES_ERROR,
            metric="fidelity_distribution",
        )

    if len(input_range) != 2 or input_range[0] >= input_range[1]:
        raise ValueError(
            f"input_range must be (min, max) with min < max, got {input_range}"
        )

    if backend not in ("pennylane", "qiskit", "cirq"):
        raise ValueError(
            f"backend must be 'pennylane', 'qiskit', or 'cirq', got {backend!r}"
        )

    # Validate parallel + sampling arguments upfront for clean ValueErrors.
    resolve_parallel_mode(parallel)
    validate_sampling(sampling)

    # Setup and sample
    rng = create_rng(seed)
    n_features = encoding.n_features

    return _sample_fidelities(
        encoding=encoding,
        n_samples=n_samples,
        n_features=n_features,
        input_range=input_range,
        rng=rng,
        backend=backend,
        verbose=False,
        parallel=parallel,
        max_workers=max_workers,
        sampling=sampling,
    )


def compute_haar_distribution(
    n_qubits: int,
    fidelity_values: NDArray[np.floating[Any]],
) -> NDArray[np.floating[Any]]:
    """Compute the Haar-random fidelity distribution.

    For a d-dimensional Hilbert space (d = 2^n_qubits), the probability
    density of fidelities between Haar-random states is:

        P_Haar(F) = (d - 1)(1 - F)^(d - 2)

    This is derived from the fact that Haar-random states are uniformly
    distributed on the complex unit sphere.

    Parameters
    ----------
    n_qubits : int
        Number of qubits (determines Hilbert space dimension d = 2^n_qubits).
    fidelity_values : NDArray[np.floating]
        Array of fidelity values at which to evaluate the distribution.
        Should be in [0, 1].

    Returns
    -------
    NDArray[np.floating]
        Probability density values at each fidelity point, normalized
        to sum to 1 (assuming fidelity_values are evenly spaced bin centers).

    Raises
    ------
    ValueError
        If ``n_qubits < 1``.

    Examples
    --------
    >>> import numpy as np
    >>> fidelities = np.linspace(0, 1, 100)
    >>> P_haar = compute_haar_distribution(n_qubits=4, fidelity_values=fidelities)
    >>> print(f"P_Haar shape: {P_haar.shape}")
    >>> print(f"P_Haar sum: {P_haar.sum():.4f}")  # Should be close to 1

    Notes
    -----
    **Physical Interpretation**

    The Haar distribution represents what we would observe if we picked
    two states uniformly at random from the Hilbert space. For large d:

    - Most pairs have very low fidelity (nearly orthogonal)
    - High fidelity pairs are exponentially rare
    - The distribution is concentrated near F = 0

    **Numerical Considerations**

    For large d (many qubits), the term (1-F)^(d-2) can cause underflow.
    We use log-space computation for d > 100 to maintain numerical stability.

    **Single Qubit Special Case**

    For d = 2 (single qubit), P_Haar(F) = 1 (uniform distribution),
    because the Bloch sphere has special geometry where all fidelities
    are equally likely.

    References
    ----------
    .. [1] Życzkowski, K., & Sommers, H.-J. (2001).
           "Induced measures in the space of mixed quantum states."
           Journal of Physics A, 34(35), 7111.
    """
    # Validate n_qubits
    if not isinstance(n_qubits, int) or n_qubits < 1:
        raise ValueError(f"n_qubits must be a positive integer, got {n_qubits}")

    # Convert to numpy array and ensure float type
    F = np.asarray(fidelity_values, dtype=np.float64)

    # Handle empty input gracefully (regardless of code path)
    if F.size == 0:
        return np.array([], dtype=np.float64)

    # Hilbert space dimension
    d = 2**n_qubits

    # Special case: single qubit (d=2)
    # P_Haar(F) = (2-1)(1-F)^(2-2) = 1 × (1-F)^0 = 1
    # Fidelity is uniformly distributed on [0, 1]
    if d == 2:
        P_haar = np.ones_like(F, dtype=np.float64)
        # Normalize
        P_haar = P_haar / (P_haar.sum() + _NUMERICAL_EPSILON)
        normalized: NDArray[np.floating[Any]] = P_haar
        return normalized

    # General case: P_Haar(F) = (d - 1)(1 - F)^(d - 2)
    # Clip (1-F) to avoid numerical issues at F=1
    one_minus_F = np.clip(1.0 - F, _NUMERICAL_EPSILON, 1.0)

    # For large d, use log-space computation to prevent overflow/underflow
    # log(P) = log(d-1) + (d-2)*log(1-F)
    if d > 100:
        log_P = np.log(d - 1) + (d - 2) * np.log(one_minus_F)
        # Subtract max for numerical stability before exp
        log_P_max: np.floating[Any] = np.max(log_P)
        P_haar = np.exp(log_P - log_P_max)
    else:
        # Direct computation for smaller d
        P_haar = (d - 1) * np.power(one_minus_F, d - 2)

    # Handle any potential NaN or Inf from computation
    P_haar = np.nan_to_num(P_haar, nan=0.0, posinf=0.0, neginf=0.0)

    # Normalize to probability distribution
    P_sum = P_haar.sum()
    if P_sum > _NUMERICAL_EPSILON:
        P_haar = P_haar / P_sum
    else:
        # Degenerate case - uniform fallback
        # This can occur due to numerical underflow when:
        # 1. n_qubits is large (d is very large, causing (1-F)^(d-2) to underflow)
        # 2. All fidelity values are very close to 1 (making (1-F) ≈ 0)
        # 3. Numerical precision issues in the log-space computation
        _logger.warning(
            "Haar distribution sum is near zero (sum=%.2e) for n_qubits=%d (d=%d). "
            "Falling back to uniform distribution. This may indicate numerical "
            "instability due to large Hilbert space dimension or fidelity values "
            "concentrated near 1.0. Consider using fewer qubits or checking input data.",
            P_sum,
            n_qubits,
            d,
        )
        P_haar = np.ones_like(P_haar) / len(P_haar)

    return cast("NDArray[np.floating[Any]]", P_haar.astype(np.float64))


