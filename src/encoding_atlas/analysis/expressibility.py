# Default number of samples for fidelity distribution estimation.
#
# RATIONALE: Expressibility requires MORE samples than other analysis metrics
# (entanglement uses 1000, trainability uses 500) because:
#
# 1. HISTOGRAM ESTIMATION: Expressibility is computed via KL divergence between
#    two histograms (sampled fidelities vs. Haar distribution). Histogram-based
#    estimators require O(n_bins²) samples for accurate bin counts.
#
# 2. SENSITIVITY TO SHAPE: KL divergence is sensitive to the tail of the
#    distribution. Insufficient samples lead to noisy tails and unreliable
#    KL estimates. With n_bins=75, we need ~67 samples per bin on average.
#
# 3. LITERATURE STANDARD: Published expressibility studies typically use
#    1000-10000 samples (Sim et al., 2019; Schuld et al., 2021).
#
# 4. COST: Each sample requires 2 circuit simulations (for the fidelity pair),
#    but no gradient computation, making samples relatively cheap.
#
# With 5000 samples and 75 bins, we achieve ~67 samples/bin, which provides
# statistically stable histogram estimation for most encodings.
_DEFAULT_N_SAMPLES: int = 5000

# Default number of histogram bins for fidelity distribution.
#
# RATIONALE: The number of bins balances resolution against statistical noise.
# Too few bins lose distribution shape; too many bins have noisy counts.
# Rule of thumb: n_bins ≈ √n_samples = √5000 ≈ 71, rounded to 75.
_DEFAULT_N_BINS: int = 75

# Minimum sample count below which results are unreliable (warning threshold).
# With 75 bins, 100 samples gives ~1.3 samples/bin, which is statistically
# marginal but may still provide rough estimates for quick exploration.
_MIN_SAMPLES_WARNING: int = 100

# Minimum sample count below which computation is refused (error threshold).
# Below 10 samples, histogram estimation is meaningless and KL divergence
# becomes numerically unstable due to empty bins.
_MIN_SAMPLES_ERROR: int = 10

# Maximum KL divergence for normalization
# Chosen to map typical KL divergence range to [0, 1]
# KL > 10 indicates extremely non-Haar distribution
_MAX_KL_DIVERGENCE: float = 10.0

# Small value to prevent numerical issues (log(0), division by zero)
# Chosen to be much smaller than typical probability values but
# larger than machine epsilon to avoid underflow
_NUMERICAL_EPSILON: float = 1e-10

# Default range for sampling input features
# [0, 2π] covers full rotation range for typical quantum gates
_DEFAULT_INPUT_RANGE: tuple[float, float] = (0.0, 2.0 * np.pi)

# Number of bootstrap samples for convergence estimation
_DEFAULT_N_BOOTSTRAP: int = 100

# Qubit threshold for performance warnings
_QUBIT_WARNING_THRESHOLD: int = 10


