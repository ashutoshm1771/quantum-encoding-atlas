# Private Helper Functions
# =============================================================================


# ---------------------------------------------------------------------------
# Process-pool worker plumbing (top-level for picklability)
# ---------------------------------------------------------------------------
#
# These globals are populated *once per worker process* by
# ``_fidelity_worker_init`` (registered as the executor's ``initializer``)
# so that the encoding instance and backend label are pickled across the
# wire just once per worker, not once per sample. The same pattern is used
# in :mod:`encoding_atlas.core.base` and proven safe there.

_FID_WORKER_ENCODING: BaseEncoding | None = None
_FID_WORKER_BACKEND: str | None = None


def _fidelity_worker_init(encoding: BaseEncoding, backend: str) -> None:
    """ProcessPoolExecutor initializer — runs once per worker process."""
    global _FID_WORKER_ENCODING, _FID_WORKER_BACKEND
    _FID_WORKER_ENCODING = encoding
    _FID_WORKER_BACKEND = backend


def _fidelity_worker_compute(
    pair: tuple[NDArray[np.floating[Any]], NDArray[np.floating[Any]]],
) -> float:
    """Worker entrypoint: compute one fidelity from an (x1, x2) pair."""
    assert (
        _FID_WORKER_ENCODING is not None and _FID_WORKER_BACKEND is not None
    ), "Process pool worker invoked before initializer ran"
    return _compute_one_fidelity(_FID_WORKER_ENCODING, pair, _FID_WORKER_BACKEND)


def _compute_one_fidelity(
    encoding: BaseEncoding,
    pair: tuple[NDArray[np.floating[Any]], NDArray[np.floating[Any]]],
    backend: str,
) -> float:
    """Simulate both inputs and return the clamped fidelity.

    Shared by the sequential, thread-pool, and process-pool code paths so
    they always produce identical floats for the same inputs.
    """
    x1, x2 = pair
    state1 = simulate_encoding_statevector(
        encoding, x1, backend=cast("Literal['pennylane', 'qiskit', 'cirq']", backend)
    )
    state2 = simulate_encoding_statevector(
        encoding, x2, backend=cast("Literal['pennylane', 'qiskit', 'cirq']", backend)
    )
    return float(np.clip(compute_fidelity(state1, state2), 0.0, 1.0))


def _sample_fidelities(
    encoding: BaseEncoding,
    n_samples: int,
    n_features: int,
    input_range: tuple[float, float],
    rng: np.random.Generator,
    backend: str,
    verbose: bool,
    parallel: ParallelArg = False,
    max_workers: int | None = None,
    sampling: SamplingMethod = "uniform",
) -> NDArray[np.floating[Any]]:
    """Sample fidelities between random input pairs.

    Generates random input pairs in batch, simulates encoding circuits,
    and computes fidelities. RNG calls are vectorized into single batch
    operations for reduced overhead.

    Parameters
    ----------
    encoding : BaseEncoding
        The encoding to analyze.
    n_samples : int
        Number of fidelity samples to generate.
    n_features : int
        Number of features in the encoding.
    input_range : tuple[float, float]
        (min, max) range for random input sampling.
    rng : np.random.Generator
        Random number generator for reproducibility.
    backend : str
        Backend for circuit simulation.
    verbose : bool
        If True, log progress.
    parallel : bool or {'thread', 'process'}, default=False
        Parallel-dispatch mode for the per-sample simulation. See
        :func:`compute_expressibility` for details.
    max_workers : int or None, default=None
        Maximum number of workers when ``parallel`` is enabled.

    Returns
    -------
    NDArray[np.floating]
        Array of fidelity values, shape ``(n_samples,)``. The numerical
        output is identical across ``parallel`` modes for a fixed
        ``rng`` — the RNG is fully consumed up front in the main
        process before any work is dispatched.

    Raises
    ------
    SimulationError
        If circuit simulation fails for any sample.
    """
    # Batch RNG generation — single call per input set. Pre-generating
    # the entire (X1, X2) batch in the main process means workers do no
    # RNG work, so the output is bit-identical across sequential /
    # thread / process modes for the same seeded ``rng``. The
    # ``sampling`` selector picks between i.i.d. uniform and
    # quasi-random Sobol' draws; both are seeded from the same ``rng``.
    X1 = generate_sample_batch(n_samples, n_features, input_range, rng, sampling)
    X2 = generate_sample_batch(n_samples, n_features, input_range, rng, sampling)

    mode = resolve_parallel_mode(parallel)

    # Sequential fast path. Also used when there's only one sample (where
    # an executor is pure overhead) and for thread mode of trivial sizes.
    if mode == "sequential" or n_samples <= 1:
        return _sample_fidelities_sequential(
            encoding, X1, X2, backend, verbose, n_samples
        )

    pairs = list(zip(X1, X2))

    # Declared up front so both pool branches share one narrowed type.
    executor: Executor
    if mode == "thread":
        # ThreadPoolExecutor shares memory; we close over ``encoding`` and
        # ``backend`` directly via the small worker callable below.
        def _one(pair: Any) -> float:
            return _compute_one_fidelity(encoding, pair, backend)

        try:
            with ThreadPoolExecutor(max_workers=max_workers) as executor:
                fidelities = np.fromiter(
                    executor.map(_one, pairs),
                    dtype=np.float64,
                    count=n_samples,
                )
        except SimulationError:
            raise
        except Exception as e:
            raise SimulationError(
                f"Failed to compute fidelities in thread pool: {e}",
                backend=backend,
                details={
                    "error_type": type(e).__name__,
                    "error_message": str(e),
                    "parallel": "thread",
                },
            ) from e
        return fidelities

    # mode == "process"
    # ProcessPoolExecutor pickles arguments per task; the
    # initializer/initargs pattern pickles the encoding once per worker
    # rather than once per sample.
    try:
        with ProcessPoolExecutor(
            max_workers=max_workers,
            initializer=_fidelity_worker_init,
            initargs=(encoding, backend),
        ) as executor:
            fidelities = np.fromiter(
                executor.map(_fidelity_worker_compute, pairs),
                dtype=np.float64,
                count=n_samples,
            )
    except SimulationError:
        raise
    except Exception as e:
        raise SimulationError(
            f"Failed to compute fidelities in process pool: {e}",
            backend=backend,
            details={
                "error_type": type(e).__name__,
                "error_message": str(e),
                "parallel": "process",
            },
        ) from e
    return fidelities


def _sample_fidelities_sequential(
    encoding: BaseEncoding,
    X1: NDArray[np.floating[Any]],
    X2: NDArray[np.floating[Any]],
    backend: str,
    verbose: bool,
    n_samples: int,
) -> NDArray[np.floating[Any]]:
    """Sequential implementation kept separate so the parallel branch in
    :func:`_sample_fidelities` stays linear-flow and easy to read."""
    fidelities: NDArray[np.float64] = np.zeros(n_samples, dtype=np.float64)
    log_interval = max(1, n_samples // 10)

    for i in range(n_samples):
        try:
            fidelities[i] = _compute_one_fidelity(encoding, (X1[i], X2[i]), backend)
        except SimulationError:
            raise
        except Exception as e:
            raise SimulationError(
                f"Failed to compute fidelity at sample {i}/{n_samples}: {e}",
                backend=backend,
                details={
                    "sample_index": i,
                    "error_type": type(e).__name__,
                    "error_message": str(e),
                },
            ) from e

        if verbose and (i + 1) % log_interval == 0:
            _logger.debug(
                "Sampled %d/%d fidelities (%.1f%%)",
                i + 1,
                n_samples,
                100.0 * (i + 1) / n_samples,
            )

    return fidelities


def _estimate_convergence(
    fidelities: NDArray[np.floating[Any]],
    n_bins: int,
    n_qubits: int,
    rng: np.random.Generator,
    n_bootstrap: int = _DEFAULT_N_BOOTSTRAP,
) -> float:
    """Estimate statistical convergence via bootstrap resampling.

    Performs bootstrap resampling to estimate the standard error of the
    KL divergence estimate. This provides a measure of how much the
    expressibility value would change with different random samples.

    Parameters
    ----------
    fidelities : NDArray[np.floating]
        Sampled fidelity values.
    n_bins : int
        Number of histogram bins.
    n_qubits : int
        Number of qubits (for Haar distribution).
    rng : np.random.Generator
        Random number generator.
    n_bootstrap : int
        Number of bootstrap samples.

    Returns
    -------
    float
        Standard error estimate for the KL divergence.
        Smaller values indicate more stable/reliable results.
    """
    n_samples = len(fidelities)

    # Quick return if too few samples for meaningful bootstrap
    if n_samples < 20:
        return float("inf")

    bootstrap_kls: NDArray[np.float64] = np.zeros(n_bootstrap, dtype=np.float64)

    # Pre-compute Haar distribution (same for all bootstrap samples)
    bin_edges = np.linspace(0.0, 1.0, n_bins + 1)
    bin_centers = (bin_edges[:-1] + bin_edges[1:]) / 2.0
    P_haar = compute_haar_distribution(n_qubits, bin_centers)
    P_haar_safe = P_haar + _NUMERICAL_EPSILON
    P_haar_safe = P_haar_safe / P_haar_safe.sum()

    bin_width = bin_edges[1] - bin_edges[0]

    for b in range(n_bootstrap):
        # Resample with replacement
        boot_indices = rng.choice(n_samples, size=n_samples, replace=True)
        boot_fidelities = fidelities[boot_indices]

        # Compute histogram for bootstrap sample
        hist, _ = np.histogram(
            boot_fidelities,
            bins=n_bins,
            range=(0.0, 1.0),
            density=True,
        )

        # Convert to probability mass
        P_boot = hist * bin_width
        P_boot_sum = P_boot.sum()
        if P_boot_sum > _NUMERICAL_EPSILON:
            P_boot = P_boot / P_boot_sum

        # Add epsilon and renormalize
        P_boot_safe = P_boot + _NUMERICAL_EPSILON
        P_boot_safe = P_boot_safe / P_boot_safe.sum()

        # Compute KL divergence
        kl_array = rel_entr(P_boot_safe, P_haar_safe)
        kl_val: float = float(np.sum(kl_array))

        # Handle numerical issues
        if np.isnan(kl_val) or np.isinf(kl_val):
            kl_val = _MAX_KL_DIVERGENCE

        bootstrap_kls[b] = kl_val

    # Return standard deviation of bootstrap KL values
    return float(np.std(bootstrap_kls, ddof=1))


def _expressibility_score_from_fidelities(
    fidelities: NDArray[np.floating[Any]],
    n_bins: int,
    n_qubits: int,
) -> float:
    """Map a fidelity sample directly to the [0, 1] expressibility score.

    Mirrors the histogram → KL → normalize pipeline used in
    :func:`compute_expressibility` exactly, so it can be invoked from
    the bootstrap CI loop and produce values commensurate with the
    main-path result. Returns ``0.0`` for fidelity arrays that the
    main path would treat as numerically degenerate (saturated bin or
    NaN/Inf KL); this is the same conservative fallback the main path
    uses.
    """
    # Histogram → density → PMF.
    hist, bin_edges = np.histogram(
        fidelities,
        bins=n_bins,
        range=(0.0, 1.0),
        density=True,
    )
    bin_width = bin_edges[1] - bin_edges[0]
    P_enc = hist * bin_width
    P_enc_sum = P_enc.sum()
    if P_enc_sum > _NUMERICAL_EPSILON:
        P_enc = P_enc / P_enc_sum
    else:
        # Degenerate case — fall back to uniform exactly as the main
        # function does. (Logging is intentionally suppressed inside
        # the bootstrap to avoid spamming users.)
        P_enc = np.ones(n_bins, dtype=np.float64) / n_bins

    bin_centers = (bin_edges[:-1] + bin_edges[1:]) / 2.0
    P_haar = compute_haar_distribution(n_qubits, bin_centers)

    P_enc_safe = P_enc + _NUMERICAL_EPSILON
    P_haar_safe = P_haar + _NUMERICAL_EPSILON
    P_enc_safe = P_enc_safe / P_enc_safe.sum()
    P_haar_safe = P_haar_safe / P_haar_safe.sum()

    kl_array = rel_entr(P_enc_safe, P_haar_safe)
    kl = float(np.sum(kl_array))
    if not np.isfinite(kl) or kl < 0.0:
        kl = max(0.0, kl) if np.isfinite(kl) else _MAX_KL_DIVERGENCE
    score = 1.0 - min(1.0, kl / _MAX_KL_DIVERGENCE)
    return float(np.clip(score, 0.0, 1.0))


def _bootstrap_expressibility_ci(
    fidelities: NDArray[np.floating[Any]],
    n_bins: int,
    n_qubits: int,
    rng: np.random.Generator,
    n_bootstrap: int,
    confidence_level: float,
) -> tuple[float, float]:
    """Percentile bootstrap CI on the expressibility score.

    The score is a non-linear function of the fidelity sample (mean of
    a histogram → KL → 1 - min(1, KL/MAX_KL)) so a simple bootstrap of
    a single scalar would miss the histogram non-linearity. We
    instead resample the fidelities and recompute the full score per
    resample.
    """
    n = len(fidelities)
    if n < 2:
        score = _expressibility_score_from_fidelities(fidelities, n_bins, n_qubits)
        return score, score

    indices = rng.integers(0, n, size=(n_bootstrap, n))
    boot_scores: NDArray[np.float64] = np.empty(n_bootstrap, dtype=np.float64)
    for b in range(n_bootstrap):
        boot_scores[b] = _expressibility_score_from_fidelities(
            fidelities[indices[b]], n_bins, n_qubits
        )
    alpha = 1.0 - float(confidence_level)
    lower = float(np.percentile(boot_scores, 100.0 * (alpha / 2.0)))
    upper = float(np.percentile(boot_scores, 100.0 * (1.0 - alpha / 2.0)))
    if upper < lower:
        upper = lower
    return lower, upper
